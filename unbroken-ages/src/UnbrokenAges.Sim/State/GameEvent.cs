{
    CityFounded,
    ProductionCompleted,
    QueueItemInvalidated,
    CityGrew,
    CityStarved,
    TechResearched,
    CivicCompleted,
    GovernorEstablished,
    CityDeclaredIndependence,
    CityFlipped,
    LoyaltyWarning,
    PowerShortage,
    ClimatePhaseChanged,
    TileFlooded,
    TileSubmerged,
    Disaster,
    ImprovementBuilt,
    TurnAdvanced,
    DivergenceChosen,
    WorldRemade,
    BloomEncroached,
    LandReclaimed,
    AscensionCompleted,
    EraEntered,
    WorldAgeBegan,
    UnitLostToAttrition,
    ProductionStalled,
    WarDeclared,
    PeaceProposed,
