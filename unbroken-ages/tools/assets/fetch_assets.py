"""Downloads every asset in assets.json into godot/assets and writes godot/assets/CREDITS.md.

python3 tools/assets/fetch_assets.py            # fetch missing files, refresh credits
Licences allowed: CC0-1.0 and CC-BY-4.0 (anything else is refused). Re-running only downloads what is missing.
"""
import json, os, sys, concurrent.futures as cf
import patchlib

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, "..", "..", "godot", "assets"))
ALLOWED = {"CC0-1.0", "CC-BY-4.0"}
manifest = json.load(open(os.path.join(HERE, "assets.json")))
lock_path = os.path.join(HERE, "assets.lock.json")
lock = json.load(open(lock_path)) if os.path.exists(lock_path) else {}


def ext_of(name):
    return os.path.splitext(name)[1].lower()


def fetch(a):
    key = f'{a["type"]}:{a["name"]}'
    for attempt in range(4):
        try:
            return fetch_once(a, key)
        except Exception as e:   # flaky network: retry, then report without aborting the whole run
            err = f"{type(e).__name__}: {e}"
            import time; time.sleep(2 + 3 * attempt)
    return key, None, err


def fetch_once(a, key):
    d = patchlib.detail(a["type"], a["id"])
    if not d:
        return key, None, f'not found: {a["id"]}'
    spdx = d["license"]["spdx"]
    if spdx not in ALLOWED:
        return key, None, f"licence {spdx} not allowed"
    variants = {v["name"]: v for v in d["variants"]}
    v = variants.get("web") or variants.get("src") or d["variants"][0]
    files = v["files"]
    if a["type"] == "material":
        files = [f for f in files if f["role"] in a.get("roles", [])]
    elif a["type"] == "hdri":
        files = [f for f in files if f["role"] == "environment"]   # the 1K .hdr, not the background preview
    out = []
    for f in files:
        suffix = f"_{f['role']}" if a["type"] == "material" else ""
        rel = os.path.join(a["dest"], a["name"] + suffix + ext_of(f["name"]))
        path = os.path.join(ROOT, rel)
        os.makedirs(os.path.dirname(path), exist_ok=True)
        if not (os.path.exists(path) and os.path.getsize(path) == f["size"]):
            patchlib.download(f["url"], path)
        out.append(rel)
    return key, {"id": a["id"], "license": spdx, "source": d["source"]["name"], "credit": d["credit"],
                 "url": d["source"].get("url"), "files": out}, None


errors = []
with cf.ThreadPoolExecutor(3) as pool:
    for key, info, err in pool.map(fetch, manifest["assets"]):
        if err:
            errors.append(f"{key}: {err}")
            print("✗", key, err)
        else:
            lock[key] = info
            print("✓", key, info["license"], ", ".join(info["files"]))
json.dump(dict(sorted(lock.items())), open(lock_path, "w"), indent=1)

by = {}
for key, info in sorted(lock.items()):
    by.setdefault(info["source"], []).append(info)
lines = ["# Asset credits", "",
         "Every third-party asset in this folder, with its licence. CC0 assets need no credit; we list them anyway.",
         "CC-BY 4.0 assets are credited exactly as their authors require. Changes: models are rescaled and tinted in-engine,",
         "textures are tiled and tinted by the terrain shader, audio is mixed and looped. Generated by tools/assets/fetch_assets.py.", ""]
for source, items in sorted(by.items()):
    lines.append(f"## {source}")
    lines.append("")
    for i in items:
        lines.append(f"- `{', '.join(i['files'])}`: {i['credit']}")
    lines.append("")
lines.append("Procedural ambience (wind and surf) is generated at runtime by `godot/scripts/Audio/Ambience.cs` and is original to this project.")
lines.append("")
lines.append("The nations' landmarks (`models/landmarks/*.glb`: pyramid, pagoda, yurt, ushnu, mosque, campanile, longhouse, kraal, stele) are original geometry generated by `tools/assets/landmarks.py`, released CC0 1.0 with the project.")
open(os.path.join(ROOT, "CREDITS.md"), "w").write("\n".join(lines) + "\n")
print(f"{len(lock)} assets, {len(errors)} errors")
sys.exit(1 if errors else 0)
