using System;
using System.Globalization;
using System.IO;
using System.Text.Json;
using System.Text.Json.Nodes;
using System.Text.RegularExpressions;

namespace AimForge.Core
{
    /// <summary>
    /// 360° CALIBRATION (2026-10-11): measure a game's sensitivity constant K instead of assuming it, then write it back where
    /// the roster is authored. Deadlock is the first customer (its K is the Source/Apex yaw, ASSUMED - see tuner.html); the
    /// same path serves any game whose K is marked estimated (Helldivers 2).
    ///
    /// K is the project's constant: K = DPI × cm/360 × sens (ev-20260910-finals-k), and the in-game number a card prints is
    /// K / (eDPI × cm) with eDPI = px/mm × 25.4 × multiplier. Two ways in, both exact:
    ///  - yaw: the game's degrees per count at sens 1 (Source 2: the m_yaw console value) -> K = 360 × 2.54 / yaw;
    ///  - a measured turn: with the card applied and the sens it printed typed in, sweep SLOWLY (inside the card's 1:1 band, so
    ///    the curve adds nothing) through whole turns back to a landmark and measure the pen travel on the tablet's glass.
    ///    K = eDPI × measured cm/360 × sens.
    /// Nothing here touches a driver or the game. The result is a tuner patch (the roster's only write path) plus an evidence
    /// record; presets.json is regenerated by the exporter as always.
    /// </summary>
    public static class Calib360
    {
        public sealed class Result
        {
            public string GameId = "", Method = "";
            public double OldK, NewK, Ratio, YawDegPerCount;
            /// the measured turn's inputs (method "turn")
            public double? PenMm, Turns, Sens, EDpi, CardCm;
            public string Summary = "";
        }

        /// From a yaw in degrees per count at sens 1.
        public static Result FromYaw(string gameId, double oldK, double yaw)
        {
            if (!(yaw > 0) || !double.IsFinite(yaw) || yaw > 10) throw new ArgumentException("yaw must be a positive number of degrees per count (Source 2 default 0.022)");
            double k = 360 * 2.54 / yaw;
            return Finish(new Result { GameId = gameId, Method = "yaw", OldK = oldK, NewK = k, YawDegPerCount = yaw });
        }

        /// From pen travel: penMm of travel for `turns` full turns, at in-game sensitivity `sens`, on a rig with px/mm and
        /// RawAccel multiplier as applied. The sweep must stay inside the card's 1:1 band (the caller states the bound).
        public static Result FromTurn(string gameId, double oldK, double penMm, double turns, double sens, double pxmm, double mult, double cardCm)
        {
            if (!(penMm > 0) || !(turns > 0) || !(sens > 0) || !(pxmm > 0) || !(mult > 0)) throw new ArgumentException("pen travel, turns, sensitivity, px/mm and multiplier must all be positive");
            double cm360 = penMm / turns / 10, edpi = pxmm * 25.4 * mult, k = edpi * cm360 * sens;
            var r = Finish(new Result { GameId = gameId, Method = "turn", OldK = oldK, NewK = k, YawDegPerCount = 360 * 2.54 / k,
                                        PenMm = penMm, Turns = turns, Sens = sens, EDpi = edpi, CardCm = cardCm });
            // a turn that measured the card's own base exactly is the same K: say so in plain terms
            r.Summary += string.Format(CultureInfo.InvariantCulture, " Measured {0:0.00} cm/360 against the card's {1:0.00}.", cm360, cardCm);
            return r;
        }

        static Result Finish(Result r)
        {
            r.Ratio = r.NewK / r.OldK;
            r.Summary = string.Format(CultureInfo.InvariantCulture, "{0}: K {1:0.0} -> {2:0.0} (x{3:0.0000}; yaw {4:0.######} deg/count).{5}",
                r.GameId, r.OldK, r.NewK, r.Ratio, r.YawDegPerCount,
                Math.Abs(r.Ratio - 1) < 0.005 ? " The assumed constant was right (within 0.5%)." : " Every card of this game prints a new in-game sensitivity after the export.");
            return r;
        }

        /// The 1:1 band a measured sweep must stay inside, in mm/s on the glass (classic: offset; LUT: the last point at gain 1).
        public static double UnityBandMmS(Preset p, double pxmm)
        {
            if (!p.IsLut) return (p.adv.offset ?? 0) * 1000 / pxmm;
            double band = 0;
            foreach (var pt in p.lut!) { if (pt[1] <= 1.0 + 1e-9) band = pt[0]; else break; }
            return band;
        }

        /// Rewrites one game's K in tuner.html (the GAMES row `{id:'<game>', ... K:<n>,`) and records the measurement on the row
        /// (kMeasured / kEvidence). Returns the new text; throws when the row cannot be found exactly once.
        public static string PatchTuner(string tunerHtml, Result r, string evidenceId)
        {
            var rx = new Regex(@"(\{id:'" + Regex.Escape(r.GameId) + @"', name:'[^']*', )K:[0-9.eE+-]+(,)( kMeasured:'[^']*', kEvidence:'[^']*',)?");
            var ms = rx.Matches(tunerHtml);
            if (ms.Count != 1) throw new InvalidDataException($"tuner.html: expected one GAMES row for '{r.GameId}', found {ms.Count}");
            string k = Math.Round(r.NewK, 1).ToString("0.0###", CultureInfo.InvariantCulture);
            string date = DateTime.Now.ToString("yyyy-MM-dd", CultureInfo.InvariantCulture);
            return rx.Replace(tunerHtml, m => m.Groups[1].Value + "K:" + k + m.Groups[2].Value + $" kMeasured:'{date}', kEvidence:'{evidenceId}',", 1);
        }

        public static string EvidenceId(string gameId, DateTime when) => "ev-" + when.ToString("yyyyMMdd", CultureInfo.InvariantCulture) + "-" + gameId + "-k";

        /// The evidence record, in the shape of the existing ev-*.json files.
        public static string EvidenceJson(Result r, string evidenceId, DateTime when, string? note)
        {
            var results = new JsonObject
            {
                ["K_measured"] = Math.Round(r.NewK, 2), ["K_before"] = r.OldK, ["ratio"] = Math.Round(r.Ratio, 5),
                ["yawDegPerCountPerSens"] = Math.Round(r.YawDegPerCount, 7),
            };
            if (r.Method == "turn")
            {
                results["penTravelMm"] = r.PenMm; results["turns"] = r.Turns; results["inGameSens"] = r.Sens; results["eDPI"] = Math.Round(r.EDpi ?? 0, 3);
                results["cm360_measured"] = Math.Round(r.PenMm!.Value / r.Turns!.Value / 10, 3); results["cm360_card"] = r.CardCm;
            }
            var o = new JsonObject
            {
                ["evidenceId"] = evidenceId, ["date"] = when.ToString("yyyy-MM-dd", CultureInfo.InvariantCulture),
                ["claim"] = $"{r.GameId} sensitivity constant K measured as {r.NewK:0.0} (was {r.OldK:0.0}, assumed).",
                ["method"] = r.Method == "yaw"
                    ? "The game's own yaw (degrees per count at sens 1) entered by the user; K = 360 x 2.54 / yaw (same constant as ev-20260910-finals-k: K = DPI x cm/360 x sens)."
                    : "AimForge 360 calibration: the card applied, the printed sens typed in game, a slow sweep inside the card's 1:1 band through whole turns back to a landmark, pen travel measured on the tablet. K = eDPI x cm/360 x sens.",
                ["results"] = results,
                ["consequence"] = "tuner.html GAMES row updated (kMeasured / kEvidence); every card of the game prints its sens from the new K after node export-presets.js.",
                ["fieldVerdict"] = note is { Length: > 0 } ? note : "pending - confirm a 360 at the new sens lands on the landmark",
            };
            return o.ToJsonString(new JsonSerializerOptions { WriteIndented = true });
        }
    }
}
